"""Stage the Kaggle kernels for the detector benchmark.

Kaggle script kernels are single files, so each kernel is bench_common.py followed by its
own script. Usage:  python stage_kernels.py <out_dir> [budget_hours]
Then, inside each staged folder:  kaggle kernels push -p .
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
USER = 'seifeldinmoheb'
PREP_SLUG = 'xcv-detbench-prep'
DATASETS = ['pkdarabi/bone-fracture-detection-computer-vision-project', 'tommyngx/fracatlas']


def stage(out, slug, title, script, header='', gpu=False, internet=False, kernel_sources=()):
    d = out / slug
    d.mkdir(parents=True, exist_ok=True)
    common = (HERE / 'bench_common.py').read_text(encoding='utf-8')
    body = (HERE / script).read_text(encoding='utf-8')
    (d / 'script.py').write_text(f'# AUTO-GENERATED by stage_kernels.py from bench_common.py + {script}\n'
                                 f'{header}\n{common}\n\n# ---- {script} ----\n{body}', encoding='utf-8')
    meta = {'id': f'{USER}/{slug}', 'title': title, 'code_file': 'script.py',
            'language': 'python', 'kernel_type': 'script', 'is_private': True,
            'enable_gpu': gpu, 'enable_internet': internet,
            'dataset_sources': [] if kernel_sources else DATASETS,
            'kernel_sources': list(kernel_sources), 'competition_sources': []}
    if gpu:
        meta['machine_shape'] = 'NvidiaTeslaT4'
    (d / 'kernel-metadata.json').write_text(json.dumps(meta, indent=2))
    print('staged', d)


def main():
    out = Path(sys.argv[1])
    budget = sys.argv[2] if len(sys.argv) > 2 else '1.5'
    stage(out, PREP_SLUG, 'xcv-detbench-prep', 'prep_data.py')
    src = [f'{USER}/{PREP_SLUG}']
    env = f"import os\nos.environ.setdefault('BUDGET_HOURS', '{budget}')\n"
    stage(out, 'xcv-detbench-rtdetr', 'xcv-detbench-rtdetr', 'train_ultralytics.py',
          header=env + "os.environ['MODEL_KEY'] = 'rtdetr-l'\n", gpu=True, internet=True, kernel_sources=src)
    stage(out, 'xcv-detbench-yolo', 'xcv-detbench-yolo', 'train_ultralytics.py',
          header=env + "os.environ['MODEL_KEY'] = 'yolo26m'\n", gpu=True, internet=True, kernel_sources=src)
    stage(out, 'xcv-detbench-frcnn', 'xcv-detbench-frcnn', 'train_faster_rcnn.py',
          header=env, gpu=True, internet=True, kernel_sources=src)


if __name__ == '__main__':
    main()
